#pragma once
#include <vector>

/** @brief Класс обработки данных.
 * @details Вычисление среднего арифметического значения вектора вещественных чисел.
 * Метод calculateMean — осуществляет вычисление среднего арифметического.
 */
class DataProcessor{
public:
    /**
     * @brief Вычисление среднего арифметического значения вектора.
     * @param[in] vec Вектор значений типа double.
     * @return Среднее арифметическое значение элементов вектора.
     *         Для пустого вектора возвращается 0.0.
     *         При переполнении вверх возвращается +inf,
     *         при переполнении вниз возвращается -inf.
     */
    double calculateMean(const std::vector<double>& vec) const;
};
