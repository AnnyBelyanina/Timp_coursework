#pragma once
#include <string>
#include <cstdint>

/** @brief Класс сетевого взаимодействия.
 * @details Реализует клиентское TCP-соединение с сервером.
 * @warning Все методы сетевых операций могут возбуждать исключения при ошибках связи.
 */

class Communicator {
private:
    int socket; ///< Дескриптор сокета для сетевого взаимодействия
public:
    /**
     * @brief Конструктор класса.
     * @param[in] fd Дескриптор файла (номер порта или существующий сокет).
     */
    explicit Communicator(int fd);
    /**
     * @brief Деструктор класса.
     * @details Автоматически закрывает сокет при уничтожении объекта, 
     * если он не был закрыт явно методом close().
     */
    ~Communicator();
    
    /**
     * @brief Установка TCP-соединения с сервером.
     * @return true при успешном установлении соединения.
     * @throw NetworkError, если не удалось создать сокет или установить соединение.
     */
    bool connect();
    
    /**
     * @brief Приём данных из сетевого соединения.
     * @details Блокирующая операция чтения указанного количества байт из сокета.
     * @param[out] buffer Буфер для записи принятых данных.
     * @param[in] size Размер буфера в байтах.
     * @throw NetworkError, если произошла ошибка приёма данных.
     */
    void receive(void* buffer, size_t size);
    
    /**
     * @brief Отправка данных в сетевое соединение.
     * @details Блокирующая операция записи указанного количества байт в сокет.
     * @param[in] buffer Буфер с отправляемыми данными.
     * @param[in] size Размер данных в байтах.
     * @throw NetworkError, если произошла ошибка отправки данных.
     */
    void send(const void* buffer, size_t size);
    
    /**
     * @brief Завершение сетевого соединения.
     * @details Закрывает сокет и освобождает связанные ресурсы.
     * @throw NetworkError, если произошла ошибка при закрытии сокета.
     */
    void close();
    
};
